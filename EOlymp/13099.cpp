bool isPrime(int n) {
    if (n < 2)
        return 0;

    for (long long d = 2; d * d <= n; d++)
        if (n % d == 0)
            return 0;

    return 1;
}

void solve() {
    int n;
    cin >> n;

    if (isPrime(n))
        cout << "1\n";
    else if (n % 2 == 0 || isPrime(n - 2))
        cout << "2\n";
    else
        cout << "3\n";
}

int main() {
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);

    int testCount;
    cin >> testCount;

    for (int test = 0; test < testCount; test++)
        solve();
}