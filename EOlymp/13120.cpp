void solve() {
    long long n, a, b, x;
    cin >> n >> a >> b >> x;

    if (a * x <= b)
        cout << n / a;
    else
        cout << n * x / b;
    cout << "\n";
}

int main() {
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);

    int testCount;
    cin >> testCount;

    for (int test = 0; test < testCount; test++)
        solve();
}