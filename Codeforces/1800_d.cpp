void solve() {
    string s;
    cin >> s >> s;

    int res = s.size() - 1;
    for (int i = 0, j = 2; j < s.size(); i++, j++)
        res -= s[i] == s[j];

    cout << res << "\n";
}

int main() {
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);

    int testCount;
    cin >> testCount;

    for (int test = 0; test < testCount; test++)
        solve();
}