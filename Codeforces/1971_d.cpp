void solve() {
    string s;
    cin >> s;

    int res = s.find("01") == -1;
    for (int i = 1; i < s.size(); i++)
        res += s[i - 1] != s[i];

    cout << res << "\n";
}

int main() {
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);

    int testCount;
    cin >> testCount;

    for (int test = 0; test < testCount; test++)
        solve();
}