void solve() {
    string s;
    cin >> s;

    reverse(s.begin(), s.end());
    for (char &c : s)
        if (c != 'w')
            c = 'p' + 'q' - c;

    cout << s << "\n";
}

int main() {
    freopen("input.txt", "r", stdin);
    freopen("output.txt", "w", stdout);

    int testCount;
    cin >> testCount;

    for (int test = 0; test < testCount; test++)
        solve();
}